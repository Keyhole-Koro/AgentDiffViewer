/**
 * Takes the README screenshots: builds a small demo repository changed by a fake Claude Code
 * session, a fake Codex session, a shell command caught by the hook and a hand edit, opens
 * `agent-diff view` on it and captures the page. Run with `npm run screenshots`.
 */
import { execFileSync, spawn } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium } from "playwright";

const ROOT = join(import.meta.dirname, "..");
const OUT = join(ROOT, "docs", "screenshots");
const home = mkdtempSync(join(tmpdir(), "adv-home-"));
const repo = join(mkdtempSync(join(tmpdir(), "adv-demo-")), "todo-api");
const env = { ...process.env, HOME: home, CLAUDE_CONFIG_DIR: "", CODEX_HOME: "", NO_COLOR: "1" };
const now = Date.now();
const at = (minutesAgo: number) => new Date(now - minutesAgo * 6e4).toISOString();

function git(...args: string[]): void {
  const past = "2026-01-05T10:00:00Z";
  execFileSync("git", args, { cwd: repo, env: { ...env, GIT_AUTHOR_DATE: past, GIT_COMMITTER_DATE: past, GIT_AUTHOR_NAME: "demo", GIT_AUTHOR_EMAIL: "demo@example.com", GIT_COMMITTER_NAME: "demo", GIT_COMMITTER_EMAIL: "demo@example.com" } });
}

function write(rel: string, lines: string[]): void {
  mkdirSync(join(repo, rel, ".."), { recursive: true });
  writeFileSync(join(repo, rel), lines.join("\n") + "\n");
}

// The repository as last committed.
const todos = [
  'import { db } from "./db.ts";',
  "",
  "export interface Todo {",
  "  id: string;",
  "  title: string;",
  "  done: boolean;",
  "}",
  "",
  "export async function createTodo(title: string): Promise<Todo> {",
  "  const todo = { id: crypto.randomUUID(), title, done: false };",
  '  await db.insert("todos", todo);',
  "  return todo;",
  "}",
  "",
  "export async function listTodos(page: number, size = 20): Promise<Todo[]> {",
  '  const all = await db.all<Todo>("todos");',
  "  return all.slice(page * size, page * size + size + 1);",
  "}",
];
const readme = ["# todo-api", "", "A small API for todos.", "", "## Run", "", "    npm start"];
const schema = ["// Generated by ./scripts/gen-schema. Do not edit.", "export const tables = [\"todos\"] as const;"];
mkdirSync(repo, { recursive: true });
git("init", "-q", "-b", "main");
write("src/todos.ts", todos);
write("README.md", readme);
write("src/schema.gen.ts", schema);
git("add", ".");
git("commit", "-q", "-m", "Initial API");

// Claude Code: due dates (an Edit and a new file).
const claudeTodos = [...todos];
claudeTodos.splice(5, 1, "  done: boolean;", "  due?: Date;");
claudeTodos.splice(9, 2, "export async function createTodo(title: string, due?: Date): Promise<Todo> {", "  const todo = { id: crypto.randomUUID(), title, done: false, due };");
const due = ["import type { Todo } from \"./todos.ts\";", "", "/** Todos past their due date, oldest first. */", "export function overdue(todos: Todo[], now = new Date()): Todo[] {", "  return todos", "    .filter((t) => !t.done && t.due && t.due < now)", "    .sort((a, b) => a.due!.getTime() - b.due!.getTime());", "}"];

// Codex: the pagination off-by-one, in the same file.
const final = [...claudeTodos];
const slice = final.findIndex((l) => l.includes("all.slice"));
final[slice] = "  return all.slice(page * size, page * size + size);";
write("src/todos.ts", final);
write("src/due.ts", due);

const claudeDir = join(home, ".claude", "projects", "-demo-todo-api");
mkdirSync(claudeDir, { recursive: true });
const cs = "4f2a9c1e-7b3d-4e8a-9c21-5d6e7f8a9b0c";
const tool = (minutes: number, name: string, input: object) => ({ type: "assistant", sessionId: cs, cwd: repo, timestamp: at(minutes), message: { content: [{ type: "tool_use", name, input }] } });
writeFileSync(
  join(claudeDir, `${cs}.jsonl`),
  [
    { type: "user", sessionId: cs, cwd: repo, timestamp: at(95), message: { content: "Add optional due dates to todos and a helper for overdue ones" } },
    { type: "ai-title", sessionId: cs, aiTitle: "Add due dates and an overdue helper" },
    tool(90, "Edit", { file_path: join(repo, "src/todos.ts"), old_string: "  done: boolean;", new_string: "  done: boolean;\n  due?: Date;" }),
    tool(88, "Edit", { file_path: join(repo, "src/todos.ts"), old_string: todos.slice(8, 10).join("\n"), new_string: claudeTodos.slice(9, 11).join("\n") }),
    tool(84, "Write", { file_path: join(repo, "src/due.ts"), content: due.join("\n") + "\n" }),
  ]
    .map((l) => JSON.stringify(l))
    .join("\n") + "\n",
);

const xs = "019a3c5e-2f1b-7d40-8e6a-b1c2d3e4f5a6";
const codexDir = join(home, ".codex", "sessions", "2026", "10", "19");
mkdirSync(codexDir, { recursive: true });
writeFileSync(
  join(codexDir, `rollout-${xs}.jsonl`),
  [
    { timestamp: at(40), type: "session_meta", payload: { id: xs, cwd: repo, timestamp: at(40) } },
    { timestamp: at(40), type: "event_msg", payload: { type: "item_completed", item: { type: "UserMessage", content: [{ type: "text", text: "Page 2 of /todos repeats the last item of page 1. Fix it." }] } } },
    { timestamp: at(35), type: "event_msg", payload: { type: "item_completed", item: { type: "FileChange", changes: { [join(repo, "src/todos.ts")]: { type: "update", unified_diff: `@@ -19 +19 @@\n-  return all.slice(page * size, page * size + size + 1);\n+  return all.slice(page * size, page * size + size);\n` } } } } },
  ]
    .map((l) => JSON.stringify(l))
    .join("\n") + "\n",
);

// A shell command in the Claude session, caught by the hook: the exact diff, no transcript needed.
const hook = (event: string) =>
  execFileSync(process.execPath, [join(ROOT, "src", "hook-entry.ts"), "--agent", "claude"], {
    cwd: repo,
    env,
    input: JSON.stringify({ session_id: cs, cwd: repo, hook_event_name: event, tool_name: "Bash", tool_use_id: "toolu_demo", tool_input: { command: "./scripts/gen-schema" } }),
  });
hook("PreToolUse");
write("src/schema.gen.ts", ["// Generated by ./scripts/gen-schema. Do not edit.", 'export const tables = ["todos"] as const;', 'export const columns = { todos: ["id", "title", "done", "due"] } as const;']);
hook("PostToolUse");

// And a hand edit nobody's transcript explains.
write("README.md", [...readme, "", "## Test", "", "    npm test"]);

const child = spawn(process.execPath, [join(ROOT, "src", "cli.ts"), "view", "--port", "0"], { cwd: repo, env });
const url = await new Promise<string>((resolve, reject) => {
  child.stdout.on("data", (d: Buffer) => {
    const m = /http:\S+/.exec(String(d));
    if (m) resolve(m[0]);
  });
  child.on("exit", () => reject(new Error("agent-diff view exited")));
});

mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch();
try {
  for (const [name, width, height, scheme] of [
    ["viewer", 1280, 800, "light"],
    ["viewer-dark", 1280, 800, "dark"],
  ] as const) {
    const page = await browser.newPage({ viewport: { width, height }, colorScheme: scheme, deviceScaleFactor: 2 });
    await page.goto(url);
    await page.waitForSelector(".session");
    await page.screenshot({ path: join(OUT, `${name}.png`) });
    console.log(`docs/screenshots/${name}.png`);
  }
} finally {
  await browser.close();
  child.kill();
  rmSync(home, { recursive: true, force: true });
  rmSync(join(repo, ".."), { recursive: true, force: true });
}
